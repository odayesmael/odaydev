import { SITE_URL } from "@/lib/site";
import { LOCALES, LOCALE_META, localePath, type Locale } from "./config";
import en from "./messages/en";
import ar from "./messages/ar";
import nl from "./messages/nl";
import tr from "./messages/tr";

const PORTFOLIO = { en, ar, nl, tr } as const;

/** Canonical + hreflang alternates for a page path like "/portfolio". */
export function localeLinks(locale: Locale, path: string) {
  return [
    { rel: "canonical", href: `${SITE_URL}${localePath(locale, path)}` },
    ...LOCALES.map((l) => ({
      rel: "alternate",
      hrefLang: l,
      href: `${SITE_URL}${localePath(l, path)}`,
    })),
    { rel: "alternate", hrefLang: "x-default", href: `${SITE_URL}${path}` },
  ];
}

/** og:url and og:locale (+ alternates) for a page. */
export function localeMeta(locale: Locale, path: string) {
  return [
    { property: "og:url", content: `${SITE_URL}${localePath(locale, path)}` },
    { property: "og:locale", content: LOCALE_META[locale].og },
    ...LOCALES.filter((l) => l !== locale).map((l) => ({
      property: "og:locale:alternate",
      content: LOCALE_META[l].og,
    })),
  ];
}

/**
 * Per-page, per-language social image (1200×630), generated by
 * scripts/og/generate.py into /public/og/<locale>/<key>.jpg.
 */
export function ogImage(locale: Locale, key: string) {
  return `${SITE_URL}/og/${locale}/${key}.jpg`;
}

export function ogImageMeta(locale: Locale, key: string, alt: string) {
  const url = ogImage(locale, key);
  return [
    { property: "og:image", content: url },
    { property: "og:image:width", content: "1200" },
    { property: "og:image:height", content: "630" },
    { property: "og:image:type", content: "image/jpeg" },
    { property: "og:image:alt", content: alt },
    { name: "twitter:card", content: "summary_large_image" },
    { name: "twitter:image", content: url },
  ];
}

/** Dates like "16 October 2026" in the page language (always Western digits). */
export function formatDate(iso: string, locale: Locale) {
  const tag = locale === "ar" ? "ar-u-nu-latn" : locale;
  return new Intl.DateTimeFormat(tag, { dateStyle: "long", timeZone: "UTC" }).format(
    new Date(`${iso}T00:00:00Z`),
  );
}

/** Home → Portfolio → page breadcrumb trail for structured data. */
export function breadcrumbs(locale: Locale, name: string, path: string) {
  return {
    "@context": "https://schema.org",
    "@type": "BreadcrumbList",
    itemListElement: [
      { "@type": "ListItem", position: 1, name: "Oday", item: `${SITE_URL}${localePath(locale, "/")}` },
      {
        "@type": "ListItem",
        position: 2,
        name: PORTFOLIO[locale].common.portfolio,
        item: `${SITE_URL}${localePath(locale, "/portfolio")}`,
      },
      { "@type": "ListItem", position: 3, name, item: `${SITE_URL}${localePath(locale, path)}` },
    ],
  };
}
